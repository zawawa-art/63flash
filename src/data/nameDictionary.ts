/**
 * Convert Romaji or alias into Japanese (Kanji / Kana) representation if available.
 */
export function getCastDisplayName(cast: { name: string; name_ja?: string; id?: string; store?: string }, lang: "en" | "ja"): string {
  if (lang === "ja") {
    // 1. Check exact ID in dictionary (e.g. for store specific disambiguation like urara)
    const idKey = (cast.id || "").toLowerCase().replace(/^cast_/, "");
    if (NAME_JA_MAP[idKey]) return NAME_JA_MAP[idKey];

    // 2. Look up directly in dictionary by normalized name
    const key = (cast.name || "").trim().toLowerCase().replace(/[^a-z0-9]/g, "");
    if (NAME_JA_MAP[key]) {
      // Special case: Spark's Urara vs ROKUSAN's Urara
      if (key === "urara" && cast.store === "super_spark") {
        return "うらら";
      }
      return NAME_JA_MAP[key];
    }

    if (cast.name_ja) return cast.name_ja;

    return cast.name;
  }
  return cast.name;
}
